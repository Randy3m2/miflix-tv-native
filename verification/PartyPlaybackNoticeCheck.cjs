'use strict';
const fs=require('fs'),assert=require('assert');
const root='app/src/main/java/com/miflix/native2/',read=f=>fs.readFileSync(root+f,'utf8');
const screen=read('ui/Screens.kt'),state=read('ui/AppState.kt'),sheet=read('ui/PartyPresentation.kt');
assert(screen.includes('if(player.playWhenReady==playing) return'));
assert.equal((screen.match(/state\.publishPartyPlaybackNotice\(playing\)/g)||[]).length,1);
assert.equal((screen.match(/userPlayback\(!player.playWhenReady\)/g)||[]).length,3);
assert(screen.includes('userPlayback(when(code)'));
const listener=screen.slice(screen.indexOf('override fun onPlayWhenReadyChanged'),screen.indexOf('override fun onEvents'));
assert(!listener.includes('publishPartyPlaybackNotice'),'automatic Media3 state changes must not emit user notices');
assert(state.includes('social.send(account,room.roomCode,"playback",action)'));
assert(state.includes('events.filter {it.kind!="playback"}'));
assert(state.includes('event.userId!=s.userId && PartyPlaybackNoticePolicy.accepts'));
assert(state.includes('delay(3500)'));assert(state.includes('partyPlaybackNotice=null;playbackNoticeSequence++'));
assert(sheet.includes(' resumed'));assert(sheet.includes(' paused'));assert(sheet.includes(' (locally)'));
assert.equal((state.match(/social\.events\(/g)||[]).length,1,'reuse the existing event poll');
assert(read('data/PartyPlaybackNoticePolicy.kt').includes('now-createdAt in -2000L..10000L'));
for(const file of ['data/PartyPlaybackNoticePolicy.kt','data/SocialRepository.kt','ui/AppState.kt','ui/Screens.kt','ui/PartyPresentation.kt','ui/UpdateNotes.kt'])assert.equal(read(file),fs.readFileSync('main/java/com/miflix/native2/'+file,'utf8'));
console.log('PASS: explicit user controls only, no automatic sync notices, fresh member events, no history replay, 3.5-second timeout, existing poll reuse, mirrors');
